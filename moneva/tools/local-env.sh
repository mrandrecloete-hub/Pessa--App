#!/usr/bin/env bash
# Writes apps/android/.env so the app talks to the LOCAL Supabase stack (started with `npm run local:start`).
# Usage: tools/local-env.sh [host]
#   host  how the PHONE or EMULATOR reaches your computer.
#         Android emulator: 10.0.2.2 (default).  Real phone on the same Wi-Fi: your computer's LAN IP, e.g. 192.168.1.20
set -euo pipefail
HOST="${1:-10.0.2.2}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
STATUS="${LOCAL_STATUS_FILE:-}"
if [ -n "$STATUS" ]; then OUT=$(cat "$STATUS"); else OUT=$(cd "$ROOT" && npx --yes supabase status -o env); fi
get() { printf '%s\n' "$OUT" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -1; }
URL=$(get API_URL)
KEY=$(get ANON_KEY); [ -n "$KEY" ] || KEY=$(get PUBLISHABLE_KEY)
if [ -z "$URL" ] || [ -z "$KEY" ]; then echo "Could not read API_URL and ANON_KEY. Is the local stack running? (npm run local:start)" >&2; exit 1; fi
URL=$(printf '%s' "$URL" | sed "s#//127.0.0.1#//$HOST#; s#//localhost#//$HOST#")
{
  echo "# Generated by tools/local-env.sh. LOCAL development only. Do not commit."
  echo "EXPO_PUBLIC_SUPABASE_URL=$URL"
  echo "EXPO_PUBLIC_SUPABASE_ANON_KEY=$KEY"
} > "$ROOT/apps/android/.env"
echo "Wrote apps/android/.env (API $URL)"
