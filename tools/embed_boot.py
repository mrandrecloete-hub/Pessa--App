#!/usr/bin/env python3
"""Embeds tools/boot_impact.js (the reload screen animation) into index.html, right after the #pesaBootMsg screen,
between /*BOOTFX:START*/ and /*BOOTFX:END*/. Run again after editing tools/boot_impact.js.   python3 tools/embed_boot.py"""
import os, re, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
idx = os.path.join(ROOT, 'index.html')
src = open(idx, encoding='utf-8').read()
js = open(os.path.join(ROOT, 'tools', 'boot_impact.js'), encoding='utf-8').read()
if '</script' in js.lower(): sys.exit('source contains </script')
block = '<script>/*BOOTFX:START (generated by tools/embed_boot.py, edit tools/boot_impact.js instead)*/\n' + js.rstrip() + '\n/*BOOTFX:END*/</script>\n'
if '/*BOOTFX:START' in src:
    src = re.sub(r'<script>/\*BOOTFX:START.*?/\*BOOTFX:END\*/</script>\n', lambda m: block, src, count=1, flags=re.S)
else:
    anchor = '<div class="app" id="app">'
    if src.count(anchor) != 1: sys.exit('anchor not found exactly once')
    src = src.replace(anchor, block + anchor, 1)
open(idx, 'w', encoding='utf-8').write(src)
print('embedded', len(block), 'bytes')
